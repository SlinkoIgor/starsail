"""Compare deterministic UTF-8 build outputs without editing the checkout."""
import argparse


def build_parser():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true',
                        help='Compare generated bytes with the checkout and report stale or missing files')
    return parser


def write_generated(path, content, *, check):
    data = content.encode('utf-8')
    if path.is_file() and path.read_bytes() == data:
        return
    if check:
        raise SystemExit(f'Generated output is stale or missing: {path}')
    path.write_bytes(data)
